package com.xu.universaltranscoder.core;

/**
 * ErrorReason 把转换过程中可能出现的失败归为有限几类，并为每一类给出：
 * 1) reason：面向用户的中文原因描述；
 * 2) suggestion：可执行的中文修复建议；
 * 3) code：稳定的机器可读编码，便于日志检索与后续统计。
 * <p>
 * 之所以要“分类”而不是直接抛原始异常字符串：MediaCodec/MediaMuxer 抛出的异常文本往往极难理解
 * （例如 “Error -38,0”），分类后用户至少知道“是权限问题还是编码器问题，以及该怎么办”。
 */
public enum ErrorReason {

    // 源文件不存在或已被移动/删除。
    FILE_NOT_FOUND("E001",
            "源文件不存在或无法打开。",
            "请用系统选择器重新选择该文件，并确认它仍然存在。"),
    // 缺少读/写授权（SAF 授权可能已失效）。
    PERMISSION_DENIED("E002",
            "应用没有读取源文件或写入所选目录的权限。",
            "请重新选择文件与输出目录，以便 Android 重新授予访问权限。"),
    // 源文件里没有目标操作所需的轨道。
    NO_TRACK("E003",
            "源文件中没有本次操作可用的媒体轨道。",
            "请选择确实包含所需音频或视频流的文件。"),
    // 视频轨缺失。
    NO_VIDEO_TRACK("E004",
            "源文件中没有视频轨。",
            "请选择视频文件，而不是音频或图片文件。"),
    // 音频轨缺失。
    NO_AUDIO_TRACK("E005",
            "源文件中没有音频轨。",
            "请选择含音频流的文件，或改用纯视频目标。"),
    // 目标容器或编码在当前设备上不被支持。
    FORMAT_UNSUPPORTED("E006",
            "当前设备不支持所请求的目标格式。",
            "请在格式列表中选择标记为受支持的目标。"),
    // 源轨道编码与目标容器不兼容（例如把 AAC 放进 WebM）。
    CODEC_INCOMPATIBLE("E007",
            "源编码无法存入所请求的容器。",
            "请改用接受该源编码的容器，或改为重新编码而不是重封装。"),
    // 编解码器初始化失败。
    CODEC_INIT_FAILED("E008",
            "系统无法初始化所需的编解码器。",
            "请尝试其它分辨率或编码，或在设置中关闭硬件编解码器。"),
    // 编解码过程中途报错。
    CODEC_ERROR("E009",
            "编解码器在处理媒体时报告了错误。",
            "请启用软件编解码器重试，或降低分辨率与码率。"),
    // 封装器报错（写轨道/写样本失败）。
    MUXER_ERROR("E010",
            "封装器拒绝了该数据流，或无法写入输出文件。",
            "请改用其它容器，或写入应用自带的输出目录。"),
    // 存储空间不足。
    STORAGE_FULL("E011",
            "没有足够可用空间写入输出文件。",
            "请释放部分存储空间后重新运行任务。"),
    // 参数非法（例如页码范围写错、缩放比例无法解析）。
    INVALID_PARAMETER("E012",
            "所提供的参数中有一项无效。",
            "请检查数值项（码率、分辨率、页码范围）后重试。"),
    // 输入类型与所选操作不匹配（例如对 PDF 使用“图片合成 PDF”）。
    INPUT_MISMATCH("E013",
            "所选输入类型与当前操作不匹配。",
            "请选择与文件匹配的操作，例如对 PDF 选择“将 PDF 页面渲染为图片”。"),
    // 解码失败（媒体文件损坏或使用了设备不支持的编码）。
    DECODE_FAILED("E014",
            "无法解码该媒体。",
            "文件可能已损坏，或使用了本设备不支持的编码。"),
    // 用户主动取消。
    CANCELED("E015",
            "任务已被用户取消。",
            "准备好后可随时重新运行该任务。"),
    // 通用 IO 错误。
    IO_ERROR("E016",
            "处理文件时发生输入/输出错误。",
            "请确认存储已挂载且可写，然后重试。"),
    // 兜底：未归类的错误。
    UNKNOWN("E999",
            "任务因未知原因失败。",
            "请打开执行日志查看原始错误文本后重试。");

    // 稳定的错误编码。
    public final String code;
    // 面向用户的原因描述（中文）。
    public final String reason;
    // 面向用户的修复建议（中文）。
    public final String suggestion;

    // 枚举构造：把三要素一次性绑定。
    ErrorReason(String code, String reason, String suggestion) {
        // 保存错误编码。
        this.code = code;
        // 保存原因描述。
        this.reason = reason;
        // 保存修复建议。
        this.suggestion = suggestion;
    }

    /**
     * 拼出可直接放进日志/状态栏的一行文本。
     */
    public String oneLine() {
        // 形如 “[E006] reason (suggestion)”。
        return "[" + code + "] " + reason + " " + suggestion;
    }
}
