// *****************************************************************************
// theme.h —— 界面主题（深色）。
// 为什么不用 .qss 资源文件：主题需要按控件状态动态调整（例如按钮禁用时的颜色），
// 用 C++ 生成样式表字符串便于集中维护，也避免额外的文件读取步骤。
// *****************************************************************************
#pragma once

// QString：返回样式表文本。
#include <QString>

// 主题工具类。
class Theme
{
public:
    // 返回整套深色样式表文本。
    static QString darkStyleSheet();

    // 返回主强调色（用于代码里少量需要与样式表保持一致的场合）。
    static QString accentColor();
};
